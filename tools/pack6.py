"""Turn baked seat frames into masked RGB565 run-length sprites + a C header for the StopWatch firmware."""
import json, os, io, sys
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.abspath(__file__))
B = os.path.join(ROOT, "bake6_out")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "firmware")
os.makedirs(OUT, exist_ok=True)
meta = json.load(open(os.path.join(B, "meta.json")))
N = meta["N"]
bg = Image.open(os.path.join(B, "bg.png")).convert("RGB")
BG = np.asarray(bg).astype(int)
THR = 14

def rgb565_swapped(a):
    a = a.astype(np.uint16)
    v = ((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)
    return ((v & 0xFF) << 8) | (v >> 8)   # byte-swapped, as LovyanGFX sprite buffers store it

def frames_for(s):
    keys = [(k, False) for k in range(N)] + ([(k, True) for k in range(N)] if s >= 3 else [])
    return {key: np.asarray(Image.open(os.path.join(B, f"s{s}_{key[0]:02d}{'_b' if key[1] else ''}.png")).convert("RGB")).astype(int) for key in keys}

def rle(img, mask):
    """uint16 stream: per row -> nRuns, then (skip, len, pixels...) for each run."""
    out = []
    px = rgb565_swapped(img)
    for y in range(mask.shape[0]):
        row = mask[y]; runs = []
        x = 0
        while x < len(row):
            if row[x]:
                x0 = x
                while x < len(row) and row[x]: x += 1
                runs.append((x0, x))
            else: x += 1
        out.append(len(runs)); prev = 0
        for x0, x1 in runs:
            out += [x0 - prev, x1 - x0]; out += px[y, x0:x1].tolist(); prev = x1
    return out

seats = []
blobs = []
total = 0
for s in range(6):
    fr = frames_for(s)
    masks = {k: (np.abs(v - BG).sum(axis=2) > THR) for k, v in fr.items()}
    uni = np.any(list(masks.values()), axis=0)
    ys, xs = np.nonzero(uni)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    entry = {"rect": [int(x0), int(y0), int(x1 - x0), int(y1 - y0)], "open": [], "blink": []}
    for (k, blink), img in sorted(fr.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        m = masks[(k, blink)][y0:y1, x0:x1]
        # grow the mask by 1px so the glow edge isn't cut hard
        g = m.copy(); g[1:] |= m[:-1]; g[:-1] |= m[1:]; g[:, 1:] |= m[:, :-1]; g[:, :-1] |= m[:, 1:]
        data = rle(img[y0:y1, x0:x1], g)
        name = f"s{s}_{'b' if blink else 'o'}{k:02d}"
        blobs.append((name, data)); total += len(data) * 2
        entry["blink" if blink else "open"].append(name)
    seats.append(entry)
    print("seat", s, entry["rect"])
print("sprite bytes:", total)

# background as JPEG (decoded once at boot)
bio = io.BytesIO(); bg.save(bio, "JPEG", quality=90, subsampling=0, optimize=True); bgj = bio.getvalue()
print("bg jpeg bytes:", len(bgj))

L = ["// generated by pack6.py", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
L.append(f"static const uint8_t BG_JPG[] = {{{','.join(map(str, bgj))}}};")
for name, data in blobs:
    L.append(f"static const uint16_t {name}[] = {{{','.join(map(str, data))}}};")
L.append(f"static const int FRAMES = {N};")
L.append("struct SeatArt { int16_t x, y, w, h; const uint16_t* open[FRAMES]; const uint16_t* blink[FRAMES]; int16_t headX, headY, chairX, chairY; };")
rows = []
for s, e in enumerate(seats):
    x, y, w, h = e["rect"]
    op = ", ".join(e["open"]); bl = ", ".join(e["blink"]) if e["blink"] else ", ".join(e["open"])
    a = meta["anchors"][s]
    rows.append(f"  {{{x}, {y}, {w}, {h}, {{{op}}}, {{{bl}}}, {a['head'][0]}, {a['head'][1]}, {a['chair'][0]}, {a['chair'][1]}}}")
L.append("static const SeatArt SEATS[6] = {\n" + ",\n".join(rows) + "\n};")
open(os.path.join(OUT, "office_art.h"), "w").write("\n".join(L) + "\n")

# preview: everyone present, frame 3, round-clipped
can = np.asarray(bg).copy()
for s, e in enumerate(seats):
    x, y, w, h = e["rect"]
    img = np.asarray(Image.open(os.path.join(B, f"s{s}_03.png")).convert("RGB"))
    m = np.abs(img.astype(int) - BG).sum(axis=2) > THR
    can[m] = img[m]
pv = Image.fromarray(can); mk = Image.new("L", (466, 466), 0); ImageDraw.Draw(mk).ellipse((0, 0, 465, 465), fill=255)
o = Image.new("RGB", (466, 466)); o.paste(pv, (0, 0), mk); o.save(os.path.join(B, "composite_preview.png"))
print("ok")
