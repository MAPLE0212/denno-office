"""M5Dial 用：bake6.py が焼いた 466×466 の絵を 240×240 に縮めて、firmware/dial/office_art_dial.h を作る。

usage: python3 pack_dial.py            （先に python3 bake6.py で bake6_out/ を作っておく）

StopWatch 用の pack6.py との違い
  - 3D をもう一度描かず、466 の絵を縮める（縮めたほうが輪郭がなめらかになる）
  - Dial には追加メモリ（PSRAM）が無いので、背景は JPEG ではなく、そのまま画面に写せる RGB565 の配列（BG_RAW）で
    フラッシュに置く。毎コマ memcpy するだけで、RAM に背景を展開しない
  - キャラのデータ形式（差分マスク付きランレングス）と SeatArt は pack6.py と同じ
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.abspath(__file__))
B = os.path.join(ROOT, "bake6_out")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "firmware", "dial")
SRC, DST = 466, 240
THR = 14


def shrink(img):
    """466 の絵を 240 に縮める（bake_chara.py の Dial 用はんこも同じ縮め方）"""
    if not isinstance(img, Image.Image):
        img = Image.fromarray(np.asarray(img).astype(np.uint8))
    return np.asarray(img.convert("RGB").resize((DST, DST), Image.LANCZOS)).astype(int)


def rgb565_swapped(a):
    a = np.clip(a, 0, 255).astype(np.uint16)
    v = ((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)
    return ((v & 0xFF) << 8) | (v >> 8)  # LovyanGFX のスプライトと同じ並び


def rle(img, mask):
    out = []
    px = rgb565_swapped(img)
    for y in range(mask.shape[0]):
        row = mask[y]
        runs, x = [], 0
        while x < len(row):
            if row[x]:
                x0 = x
                while x < len(row) and row[x]: x += 1
                runs.append((x0, x))
            else:
                x += 1
        out.append(len(runs))
        prev = 0
        for x0, x1 in runs:
            out += [x0 - prev, x1 - x0]
            out += px[y, x0:x1].tolist()
            prev = x1
    return out


def grow(m):
    """グローの縁を切らないよう、マスクを 1px 広げる"""
    g = m.copy(); g[1:] |= m[:-1]; g[:-1] |= m[1:]; g[:, 1:] |= m[:, :-1]; g[:, :-1] |= m[:, 1:]
    return g


if __name__ == "__main__":
    meta = json.load(open(os.path.join(B, "meta.json")))
    N = meta["N"]
    BG = shrink(Image.open(os.path.join(B, "bg.png")))

    seats, blobs, total = [], [], 0
    shown = {}
    for s in range(6):
        keys = [(k, False) for k in range(N)] + ([(k, True) for k in range(N)] if s >= 3 else [])
        fr = {key: shrink(Image.open(os.path.join(B, f"s{s}_{key[0]:02d}{'_b' if key[1] else ''}.png"))) for key in keys}
        masks = {k: np.abs(v - BG).sum(axis=2) > THR for k, v in fr.items()}
        ys, xs = np.nonzero(np.any(list(masks.values()), axis=0))
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
        entry = {"rect": [int(x0), int(y0), int(x1 - x0), int(y1 - y0)], "open": [], "blink": []}
        for (k, blink), img in sorted(fr.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            data = rle(img[y0:y1, x0:x1], grow(masks[(k, blink)][y0:y1, x0:x1]))
            name = f"s{s}_{'b' if blink else 'o'}{k:02d}"
            blobs.append((name, data)); total += len(data) * 2
            entry["blink" if blink else "open"].append(name)
        seats.append(entry)
        shown[s] = (fr[(3, False)], masks[(3, False)])
        print("seat", s, entry["rect"])
    print("sprite bytes:", total)

    bg_raw = rgb565_swapped(BG).flatten()
    sc = DST / SRC
    L = ["// generated by pack_dial.py（M5Dial 用、240x240）", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
    L.append(f"static const uint16_t BG_RAW[{DST * DST}] = {{{','.join(map(str, bg_raw.tolist()))}}};")
    for name, data in blobs:
        L.append(f"static const uint16_t {name}[] = {{{','.join(map(str, data))}}};")
    L.append(f"static const int FRAMES = {N};")
    L.append("struct SeatArt { int16_t x, y, w, h; const uint16_t* open[FRAMES]; const uint16_t* blink[FRAMES]; int16_t headX, headY, chairX, chairY; };")
    rows = []
    for s, e in enumerate(seats):
        x, y, w, h = e["rect"]
        op = ", ".join(e["open"]); bl = ", ".join(e["blink"]) if e["blink"] else op
        a = meta["anchors"][s]
        hx, hy, cx, cy = (round(v * sc) for v in (a["head"][0], a["head"][1], a["chair"][0], a["chair"][1]))
        rows.append(f"  {{{x}, {y}, {w}, {h}, {{{op}}}, {{{bl}}}, {hx}, {hy}, {cx}, {cy}}}")
    L.append("static const SeatArt SEATS[6] = {\n" + ",\n".join(rows) + "\n};")
    open(os.path.join(OUT, "office_art_dial.h"), "w").write("\n".join(L) + "\n")

    # 見本：全員在席の 3 コマ目を、奥 → 手前の順に重ねて丸く切る
    can = BG.copy()
    for s in (3, 4, 5, 0, 1, 2):
        img, m = shown[s]
        can[m] = img[m]
    mk = Image.new("L", (DST, DST), 0); ImageDraw.Draw(mk).ellipse((0, 0, DST - 1, DST - 1), fill=255)
    o = Image.new("RGB", (DST, DST)); o.paste(Image.fromarray(can.astype(np.uint8)), (0, 0), mk)
    o.save(os.path.join(B, "composite_preview_dial.png"))
    print("ok")
